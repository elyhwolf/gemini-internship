  // Handle Choice Selection
  function handleChoice(userChoice) {
    if (choiceAiBtn.disabled) return;

    clearInterval(timerInterval);
    const qTime = (Date.now() - qStartTime) / 1000;
    totalTime += qTime;

    const q = QUESTIONS[currentQIndex];
    const isCorrect = userChoice === q.answer;

    choiceAiBtn.disabled = true;
    choiceRealBtn.disabled = true;

    // Button states
    if (userChoice === 'ai') {
      choiceAiBtn.classList.add(isCorrect ? 'selected-correct' : 'selected-wrong');
    } else {
      choiceRealBtn.classList.add(isCorrect ? 'selected-correct' : 'selected-wrong');
    }

    // Update Step Node
    const node = document.getElementById(`stepNode_${currentQIndex}`);
    if (node) {
      node.className = `step-node ${isCorrect ? 'passed-correct' : 'passed-wrong'}`;
    }

    if (isCorrect) {
      score++;
      earnedXp += 15;
      soundFX.playCorrect();
      verdictBanner.className = 'verdict-banner is-correct';
      verdictBadge.textContent = '✓ CORRECT VERDICT';
      verdictXp.textContent = '+15 XP';
    } else {
      soundFX.playWrong();
      verdictBanner.className = 'verdict-banner is-wrong';
      verdictBadge.textContent = '✗ INCORRECT VERDICT';
      verdictXp.textContent = '+0 XP';
    }

    // Update scoreboard
    scoreVal.textContent = `${score} / ${QUESTIONS.length}`;
    userXpDisplay.textContent = `+${earnedXp} XP`;

    // Populate forensic banner
    verdictTitle.textContent = q.title;
    verdictExplanation.textContent = q.explanation;
    cluesList.innerHTML = '';
    q.clues.forEach(clue => {
      const li = document.createElement('li');
      li.textContent = clue;
      cluesList.appendChild(li);
    });

    if (currentQIndex === QUESTIONS.length - 1) {
      nextBtnText.textContent = 'VIEW FINAL FORENSIC DOSSIER';
    } else {
      nextBtnText.textContent = 'CONTINUE TO NEXT CASE';
    }

    verdictBanner.classList.remove('hidden');

    userAnswers.push({
      qIndex: currentQIndex,
      userChoice,
      isCorrect,
      time: qTime
    });

    // Scroll gently to verdict banner if needed
    verdictBanner.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }

